<#
.SYNOPSIS
Point this computer's monitors at an input.

.DESCRIPTION
    trigger-kvm.ps1 pull                 pull every configured monitor to THIS computer
    trigger-kvm.ps1 to mac               point them at the computer called "mac"
    trigger-kvm.ps1 pull -Only lg        one monitor only
    trigger-kvm.ps1 pull -WhatIf         resolve and build the packets, send nothing

A monitor's inputs are named after the computers plugged into them, and that one map
answers both verbs:

    display.lg.input.0xD0 = pc
    display.lg.input.0xD1 = mac
    computer.this          = pc

`pull` points every configured monitor at `computer.this`. `to mac` points them at
`mac`. Same lookup, same code path, different name -- there is no second table, so
the two can never disagree about where a computer is.

`to` is MANUAL ONLY: the trigger cannot reach it by any path. A name that has gone
stale -- someone moved a cable on the other computer -- can therefore only spoil a
command you typed and are watching, never an automatic switch. That separation is
why the two verbs are distinct rather than one verb with an optional argument.

Everything is resolved BEFORE anything is sent. A computer that two displays know
about and a third does not moves neither: a half-applied arrangement leaves the desk
in a state nobody configured, and you have to work out which half landed.

Configuration lives in %LOCALAPPDATA%\trigger-kvm\config, generated by install.ps1
and safe to edit by hand -- or wherever -Config says, which is what the installed
watcher passes down. Display edits take effect on the next switch; trigger edits
when the watcher next starts, and `trigger-kvm restart` does that. Nothing is
baked into the scheduled task but the paths.

Two axes, and they are different questions. WHAT is sent:

  method = standard   standard DDC/CI     -- VCP 0x60
  method = lg-alt     LG's sidechannel    -- I2C source 0x50, VCP 0xF4, for panels
                      whose standard input control is stubbed

and HOW it gets there:

  transport = nvapi   aimed raw I2C at one GPU output. Works with NO DESKTOP, so
                      it is the only one the boot tier can use -- and the only one
                      that can carry lg-alt. NVIDIA outputs only.
  transport = dxva2   Windows' own DDC/CI stack. ANY adapter, which is the point
                      of it, but it needs a desktop and cannot express an I2C
                      source byte at all, so it carries `standard` and nothing else.

Absent, transport means nvapi, so configs written before it existed are unchanged.
Neither is a spray and neither is a fallback: the transport is configuration,
chosen once and confirmed once by eye, and nothing tries one and falls through to
the other at switch time. See ..\ideas\nvapi-transport.md for NVAPI's function ids,
struct traps and provenance, and ..\docs\decisions\003 for why dxva2 exists.

Identity is ONE key for both: the EDID manufacturer and product, which NVAPI reads
off the GPU output and dxva2 reads out of the PnP interface path. Never the GDI
name or the full interface path -- moving a cable between adapters changes both
while the EDID pair holds. Each write is AIMED at the single output that
identifies as the panel, and anything other than exactly one match is refused.

That refusal is load-bearing for dxva2 specifically. In session 0 user32 reports a
PHANTOM monitor rather than none, with no interface path at all -- so it fails by
resolving onto a fiction rather than by erroring. Matching on EDID turns that into
a clean refusal. NVAPI has no such problem and needs no desktop, which is why a
dxva2 panel cannot be covered before login and the tier says so.

NEVER verify a switch by reading a VCP value back -- see ..\displays.toml for why.
Both monitors switched correctly during macOS testing while reads said they had
not. Writes are fire-and-forget; there are deliberately no reads in this script.

SAFETY: the I2C source address 0x50 is LG's service channel. It appears in exactly
one function, NvDdc.WriteLgInput, which refuses to run unless the target's EDID
manufacturer is GSM (0x1E6D). The source byte is not a parameter of any public
method, so the sidechannel cannot be aimed at another vendor's panel by any caller.
Note that `method = lg-alt` in the config does NOT bypass that gate: setting it on
a non-GSM panel makes the write throw, it does not make the write happen.
#>

[CmdletBinding(SupportsShouldProcess = $true)]
param(
    # pull -- point every configured monitor at THIS machine. The only thing the
    #         trigger ever runs.
    # to   -- point them at another machine, by name. Manual use only.
    [Parameter(Position = 0)]
    # Only the switching verbs run here; the management ones are install.ps1's,
    # and `trigger-kvm.cmd` routes between the two so a user types one command
    # and never has to know there are two scripts. Checked against $VERBS in
    # config.ps1 below rather than by a ValidateSet, because the verb surface is
    # written down once and a ValidateSet cannot read it.
    [string]$Command = 'pull',

    # Which machine, for `to`. A name from the config's input map -- `mac`, say.
    [Parameter(Position = 1)]
    [string]$Computer,

    # `set` only: the input value to send to the single display named by -Only.
    #
    # This exists for the installer's guided input discovery, where the whole point
    # is trying a candidate value and looking at the screen. It is deliberately NOT
    # routed by trigger-kvm.cmd, so it is not part of the public verb surface --
    # a general "write any value" command invites poking at monitors, which is the
    # habit this project's first hard rule exists to discourage.
    #
    # It grants nothing the transport would not already allow: the 0x50 sidechannel
    # stays behind NvDdc.WriteLgInput's GSM check, so `set` on a non-LG panel with
    # method=lg-alt throws exactly as `pull` would.
    [string]$Value,

    # `list` only: emit "vendor|product|mfg|connector|serial" rows via the PIPELINE
    # instead of the human table, so callers can consume it.
    #
    # This exists because the human output uses Write-Host, which writes to the host
    # and NOT to stdout -- so `& trigger-kvm.ps1 list` returns nothing to a caller,
    # silently. Same shape as event-watch.ps1 -ListBluetooth.
    [switch]$Raw,

    # Move one monitor only, by its configured label. ..\AGENTS.md rule 4 needs this:
    # moving every monitor at once can take the last display out from under the
    # terminal. 'all' means every configured display.
    [string]$Only = 'all',

    # DDC is lossy and these writes are idempotent, so a repeat is free.
    [int]$Tries = 2,

    # Append to this file as well as writing to the host. usb-watch.ps1 passes its
    # own log through, so a fired switch is recorded beside the arrival that caused
    # it. Unset for manual runs, where the host output is what you want.
    [string]$LogFile,

    # Generated by the installer; hand-editable. Format is in config.ps1.
    [string]$Config
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

# --- configuration ----------------------------------------------------------

# The shared vocabulary: the config reader, the two value converters, the verb
# surface and the transport table. Dot-sourced rather than duplicated, because
# three consumers parsing the same format independently is a drift risk where
# the watcher and the switcher silently disagree about what is configured.
#
# ConvertTo-Byte and ConvertTo-Word return $null on anything unrecognised rather
# than guessing. A misparsed input value is a write aimed at the wrong input,
# and a misparsed EDID id is a write aimed at the wrong PANEL. $null is
# "refuse", never zero.
. (Join-Path $PSScriptRoot 'config.ps1')

# The verb surface is $VERBS', so an unknown verb gets this program's own
# message rather than a binding error naming a set nobody wrote down twice.
if ($Command -notin (Get-Verbs -Where 'switch')) {
    Write-Host ("trigger-kvm: no such verb ""{0}""." -f $Command)
    Write-Host ("this script runs: {0}" -f ((Get-Verbs -Where 'switch') -join ', '))
    Write-Host 'the rest are install.ps1''s; `trigger-kvm <verb>` routes to whichever owns it.'
    exit 2
}

# Every display the config declares, in file order.
# display.<label>.input.<value> = <machine>, read back as machine -> value.
#
# Two inputs naming the same machine on one panel is a refusal rather than a coin
# toss: it means someone edited the file wrongly, and picking one of them would
# switch to an input the user did not mean on a desk they cannot see.
function Get-InputMap {
    param([System.Collections.IDictionary]$Cfg, [string]$Label)

    $map = @{}
    foreach ($k in ($Cfg.Keys | Sort-Object)) {
        if ($k -notmatch ('^display\.' + [regex]::Escape($Label) + '\.input\.(.+)$')) { continue }
        $value = ConvertTo-Byte $Matches[1]
        $name  = "$($Cfg[$k])".Trim().ToLower()
        if ($null -eq $value -or -not $name) { continue }
        if ($map.Contains($name)) {
            $map[$name] = 'AMBIGUOUS'
            continue
        }
        $map[$name] = $value
    }
    return $map
}

function Get-ConfiguredDisplays {
    param([System.Collections.IDictionary]$Cfg)
    $labels = @($Cfg.Keys |
        Where-Object { $_ -match '^display\.([^.]+)\.vendor$' } |
        ForEach-Object { $Matches[1] } |
        Sort-Object -Unique)

    $out = @()
    foreach ($l in $labels) {
        # No casts here on purpose. [int]$null is 0, which would turn an
        # unparseable EDID id into a silent match against vendor 0x0000 -- exactly
        # the kind of quiet mis-aim this project refuses to permit. Keep $null and
        # let the caller refuse.
        $out += [PSCustomObject]@{
            Label   = $l
            Vendor  = ConvertTo-Word $Cfg["display.$l.vendor"]
            Product = ConvertTo-Word $Cfg["display.$l.product"]
            Name    = $(if ($Cfg.Contains("display.$l.name")) { $Cfg["display.$l.name"] } else { $l })
            Method  = $(if ($Cfg.Contains("display.$l.method")) { $Cfg["display.$l.method"].ToLower() } else { 'standard' })
            # Absent means nvapi -- the transport this platform had before there
            # were two -- so a config written before the key existed is unchanged
            # and needs no rewrite (specs/config-format.md). An unrecognised value
            # is NOT defaulted here; Switch-Display refuses it by name, because
            # defaulting would send the write down a path nobody confirmed by eye.
            Transport = $(if ($Cfg.Contains("display.$l.transport")) { "$($Cfg["display.$l.transport"])".Trim().ToLower() } else { 'nvapi' })
            # machine name (lower-cased) -> input value. The whole map: which
            # machine is on which input of this panel. `pull` and `to` are the same
            # lookup against it, differing only in which name they look up.
            Inputs  = (Get-InputMap -Cfg $Cfg -Label $l)
        }
    }
    return $out
}

# --- logging ---------------------------------------------------------------

function Write-Log {
    param([string]$Message)
    $line = '{0} trigger-kvm: {1}' -f (Get-Date -Format 'HH:mm:ss'), $Message
    Write-Host $line
    if ($LogFile) {
        # The watcher appends to the same file, so a write can briefly collide.
        for ($i = 0; $i -lt 3; $i++) {
            try { Add-Content -LiteralPath $LogFile -Value $line -ErrorAction Stop; break }
            catch { Start-Sleep -Milliseconds 50 }
        }
    }
}

# --- LG: aimed raw I2C through NVAPI ---------------------------------------
#
# Function ids and struct layouts from fiddyschmitt/SimpleKVM (MIT), with
# Initialize / EnumPhysicalGPUs / I2CWrite independently corroborated by
# meer-cha/lg-input-switch. Enumeration and EDID reads were verified against this
# hardware on 2026-08-30 in four contexts, including session 0 with no desktop and
# an at-startup task after a cold boot. The aimed write itself was confirmed
# visually, both directions, from an inactive link. See ..\ideas\nvapi-transport.md.

$TransportSource = @'
using System;
using System.Collections.Generic;
using System.Runtime.InteropServices;

// One connected output, identified purely by the EDID the GPU read from it.
public class NvDisplay {
    public IntPtr Gpu;
    public uint   OutputId;      // legacy single-bit output id -- what I2CWrite takes
    public int    DisplayId;
    public string Connector;
    public ushort EdidVendor;
    public ushort EdidProduct;
    public uint   EdidSerial;
    public string EdidName;      // the model name the panel reports, or ""

    public override string ToString() {
        return string.Format("outputId=0x{0:X8} connector={1} edid=0x{2:X4}:0x{3:X4} serial=0x{4:X8}",
                             OutputId, Connector, EdidVendor, EdidProduct, EdidSerial);
    }
}

public static class NvDdc {

    // ---- loader ------------------------------------------------------------
    // PowerShell 5.1 is .NET Framework, which has no NativeLibrary; use kernel32.

    [DllImport("kernel32.dll", CharSet = CharSet.Ansi, SetLastError = true)]
    static extern IntPtr LoadLibrary(string lpFileName);

    [DllImport("kernel32.dll", CharSet = CharSet.Ansi, SetLastError = true, BestFitMapping = false)]
    static extern IntPtr GetProcAddress(IntPtr hModule, string procName);

    const uint NVAPI_INITIALIZE                         = 0x0150E828;
    const uint NVAPI_ENUMPHYSICALGPUS                   = 0xE5AC921F;
    const uint NVAPI_GPU_GETCONNECTEDDISPLAYIDS         = 0x0078DBA2;
    const uint NVAPI_GPU_GETEDID                        = 0x37D32E69;
    const uint NVAPI_SYS_GETGPUANDOUTPUTIDFROMDISPLAYID = 0x112BA1A5;
    const uint NVAPI_I2CWRITE                           = 0xE812EB07;

    const int NVAPI_MAX_PHYSICAL_GPUS = 64;

    // DDC/CI slave address 0x37, shifted left one bit for a write: 0x6E.
    const byte DDC_I2C_ADDRESS = 0x6E;

    // The normal DDC/CI host source address. Everything except the LG's input uses
    // this; it is what dxva2's SetVCPFeature puts on the wire too.
    const byte STD_I2C_SOURCE = 0x51;

    // LG's manufacturer sidechannel. Standard DDC/CI is source 0x51 / VCP 0x60;
    // on this panel VCP 0x60 is stubbed and input lives here instead.
    const byte LG_I2C_SOURCE = 0x50;
    const byte LG_VCP_INPUT  = 0xF4;

    // The one vendor whose panels may be sent LG_I2C_SOURCE. 0x50 is a service /
    // factory channel; sweeping it has bricked LG monitors, and what it means on
    // another vendor's panel is unknown. See ..\AGENTS.md hard rule 1.
    const ushort EDID_VENDOR_GSM = 0x1E6D;

    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]
    delegate IntPtr QueryInterface_t(uint id);
    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]
    delegate int Initialize_t();
    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]
    delegate int EnumPhysicalGPUs_t([Out] IntPtr[] handles, out int count);
    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]
    delegate int GetConnectedDisplayIds_t(IntPtr gpu, [In, Out] NV_GPU_DISPLAYIDS[] ids, ref int count, int flags);
    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]
    delegate int GetEDID_t(IntPtr gpu, int outputId, ref NV_EDID edid);
    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]
    delegate int GetGpuAndOutputIdFromDisplayId_t(uint displayId, out IntPtr gpu, out uint outputId);
    [UnmanagedFunctionPointer(CallingConvention.Cdecl)]
    delegate int I2CWrite_t(IntPtr gpu, ref NV_I2C_INFO info);

    // Struct version is sizeof(struct) | (version << 16). Get the layout wrong and
    // the encoded size is wrong and NvAPI rejects the call with an obscure error.
    [StructLayout(LayoutKind.Sequential)]
    public struct NV_GPU_DISPLAYIDS {
        public int version;
        public int connectorType;
        public int displayId;
        public uint flags;
    }

    [StructLayout(LayoutKind.Sequential)]
    public struct NV_EDID {
        public int version;
        [MarshalAs(UnmanagedType.ByValArray, SizeConst = 256)]
        public byte[] edidData;
        public int edidSize;
        public uint edidId;   // NV_EDID_V3 has these two extra fields; without them
        public uint offset;   // the size-encoded version is wrong and NvAPI refuses
    }

    // NV_I2C_INFO_V3. The trailing bIsPortIdSet is the same class of trap as
    // NV_EDID's edidId/offset: omit it and the encoded size is wrong. On x64 this
    // must come out at 64 bytes, i.e. version 0x00030040 -- checked at runtime.
    [StructLayout(LayoutKind.Sequential)]
    public struct NV_I2C_INFO {
        public uint   version;
        public uint   displayMask;      // the legacy single-bit output id
        public byte   bIsDDCPort;
        public byte   i2cDevAddress;
        public IntPtr pbI2cRegAddress;
        public uint   regAddrSize;
        public IntPtr pbData;
        public uint   cbSize;
        public uint   i2cSpeed;         // deprecated, must be 0xFFFF
        public uint   i2cSpeedKhz;
        public byte   portId;
        public uint   bIsPortIdSet;
    }

    static QueryInterface_t _qi;
    static Initialize_t _init;
    static EnumPhysicalGPUs_t _enumGpus;
    static GetConnectedDisplayIds_t _getDisplayIds;
    static GetEDID_t _getEdid;
    static GetGpuAndOutputIdFromDisplayId_t _getOutputId;
    static I2CWrite_t _i2cWrite;
    static bool _ready;

    static T Resolve<T>(uint id) where T : class {
        IntPtr p = _qi(id);
        if (p == IntPtr.Zero) return null;
        return Marshal.GetDelegateForFunctionPointer(p, typeof(T)) as T;
    }

    public static string Init() {
        if (_ready) return "OK";

        if (!Environment.Is64BitProcess)
            return "FAIL: not a 64-bit process; nvapi64.dll cannot be loaded";

        IntPtr lib = LoadLibrary("nvapi64.dll");
        if (lib == IntPtr.Zero)
            return "FAIL: nvapi64.dll not found (no NVIDIA driver?)";

        IntPtr qi = GetProcAddress(lib, "nvapi_QueryInterface");
        if (qi == IntPtr.Zero) qi = GetProcAddress(lib, "nvapi64_QueryInterface");
        if (qi == IntPtr.Zero)
            return "FAIL: nvapi_QueryInterface not exported by nvapi64.dll";

        _qi = (QueryInterface_t)Marshal.GetDelegateForFunctionPointer(qi, typeof(QueryInterface_t));

        _init          = Resolve<Initialize_t>(NVAPI_INITIALIZE);
        _enumGpus      = Resolve<EnumPhysicalGPUs_t>(NVAPI_ENUMPHYSICALGPUS);
        _getDisplayIds = Resolve<GetConnectedDisplayIds_t>(NVAPI_GPU_GETCONNECTEDDISPLAYIDS);
        _getEdid       = Resolve<GetEDID_t>(NVAPI_GPU_GETEDID);
        _getOutputId   = Resolve<GetGpuAndOutputIdFromDisplayId_t>(NVAPI_SYS_GETGPUANDOUTPUTIDFROMDISPLAYID);
        _i2cWrite      = Resolve<I2CWrite_t>(NVAPI_I2CWRITE);

        List<string> missing = new List<string>();
        if (_init          == null) missing.Add("NvAPI_Initialize");
        if (_enumGpus      == null) missing.Add("NvAPI_EnumPhysicalGPUs");
        if (_getDisplayIds == null) missing.Add("NvAPI_GPU_GetConnectedDisplayIds");
        if (_getEdid       == null) missing.Add("NvAPI_GPU_GetEDID");
        if (_getOutputId   == null) missing.Add("NvAPI_SYS_GetGpuAndOutputIdFromDisplayId");
        if (_i2cWrite      == null) missing.Add("NvAPI_I2CWrite");
        if (missing.Count > 0)
            return "FAIL: QueryInterface returned NULL for: " + string.Join(", ", missing);

        int size = Marshal.SizeOf(typeof(NV_I2C_INFO));
        if (size != 64)
            return string.Format("FAIL: NV_I2C_INFO marshals to {0} bytes, expected 64 " +
                                 "(version would encode as 0x{1:X8}, not 0x00030040). " +
                                 "The struct layout is wrong; NvAPI would reject the call.",
                                 size, size | (3 << 16));

        int rc = _init();
        if (rc != 0)
            return "FAIL: NvAPI_Initialize returned " + rc;

        _ready = true;
        return "OK";
    }

    // EDID manufacturer id is three 5-bit letters packed big-endian in bytes 8-9.
    // The model name the panel reports about itself: EDID descriptor tag 0xFC, in
    // one of the four 18-byte blocks at 54/72/90/108. Asking the hardware beats any
    // table we could ship -- a database only ever knows the monitors we have met,
    // and this knows every monitor. Returns "" when the descriptor is absent, which
    // is legal and not rare on cheap panels.
    public static string DecodeName(byte[] edid, int size) {
        if (edid == null || size < 128) return "";
        for (int b = 54; b + 18 <= 126; b += 18) {
            // A descriptor with a non-zero pixel clock is a timing block, not text.
            if (edid[b] != 0 || edid[b + 1] != 0 || edid[b + 2] != 0) continue;
            if (edid[b + 3] != 0xFC) continue;
            var sb = new System.Text.StringBuilder();
            for (int i = b + 5; i < b + 18; i++) {
                byte c = edid[i];
                if (c == 0x0A) break;              // the field is newline-terminated
                if (c < 0x20 || c > 0x7E) continue;
                sb.Append((char)c);
            }
            return sb.ToString().Trim();
        }
        return "";
    }

    public static string DecodeMfg(ushort id) {
        char a = (char)(((id >> 10) & 0x1F) + 64);
        char b = (char)(((id >> 5)  & 0x1F) + 64);
        char c = (char)((id         & 0x1F) + 64);
        return new string(new char[] { a, b, c });
    }

    static string ConnectorName(int t) {
        switch (t) {
            case 0:  return "Uninitialized";
            case 1:  return "VGA";
            case 2:  return "Component";
            case 3:  return "SVideo";
            case 4:  return "HDMI";
            case 5:  return "DVI";
            case 6:  return "LVDS";
            case 7:  return "DisplayPort";
            case 8:  return "Composite";
            default: return "Unknown(" + t + ")";
        }
    }

    // Every connected output on every NVIDIA GPU, with its EDID decoded.
    //
    // Deliberately NOT correlated against the Windows display list: in session 0
    // user32 reports a phantom monitor rather than nothing, so any such match is
    // against a fiction. NVAPI is the sole identity source. See .\AGENTS.md.
    public static List<NvDisplay> Enumerate() {
        var found = new List<NvDisplay>();

        IntPtr[] gpus = new IntPtr[NVAPI_MAX_PHYSICAL_GPUS];
        int gpuCount = 0;
        if (_enumGpus(gpus, out gpuCount) != 0 || gpuCount == 0) return found;

        int versionDisplayIds = Marshal.SizeOf(typeof(NV_GPU_DISPLAYIDS)) | (3 << 16);
        int versionEdid       = Marshal.SizeOf(typeof(NV_EDID))           | (3 << 16);

        for (int g = 0; g < gpuCount; g++) {
            IntPtr gpu = gpus[g];

            // Two-call pattern: null array first to learn the count.
            int count = 0;
            if (_getDisplayIds(gpu, null, ref count, 0) != 0 || count == 0) continue;

            var ids = new NV_GPU_DISPLAYIDS[count];
            for (int i = 0; i < count; i++) ids[i].version = versionDisplayIds;
            if (_getDisplayIds(gpu, ids, ref count, 0) != 0) continue;

            for (int d = 0; d < count; d++) {
                // bit 6 (0x40) is isConnected. Do NOT gate on isActive (bit 2):
                // it varied over time within a single session during phase 1.
                if ((ids[d].flags & 0x40) == 0) continue;

                IntPtr owner;
                uint outputId;
                if (_getOutputId((uint)ids[d].displayId, out owner, out outputId) != 0) continue;
                if (outputId == 0) continue;

                // GetEDID and I2CWrite take the LEGACY single-bit output id, not
                // the displayId that GetConnectedDisplayIds returns.
                var edid = new NV_EDID();
                edid.version  = versionEdid;
                edid.edidData = new byte[256];
                if (_getEdid(gpu, (int)outputId, ref edid) != 0) continue;
                if (edid.edidSize < 18) continue;
                if (edid.edidData[0] != 0x00 || edid.edidData[1] != 0xFF) continue;

                var nd = new NvDisplay();
                nd.Gpu         = gpu;
                nd.OutputId    = outputId;
                nd.DisplayId   = ids[d].displayId;
                nd.Connector   = ConnectorName(ids[d].connectorType);
                nd.EdidVendor  = (ushort)((edid.edidData[8] << 8) | edid.edidData[9]);
                nd.EdidProduct = (ushort)(edid.edidData[10] | (edid.edidData[11] << 8));
                nd.EdidSerial  = (uint)(edid.edidData[12] | (edid.edidData[13] << 8)
                                      | (edid.edidData[14] << 16) | (edid.edidData[15] << 24));
                nd.EdidName    = DecodeName(edid.edidData, edid.edidSize);
                found.Add(nd);
            }
        }
        return found;
    }

    // A DDC/CI SetVCP message: [source, 0x84, 0x03, vcp, valueMsb, valueLsb, checksum]
    // Checksum is 0x6E XOR every preceding byte.
    static byte[] BuildSetVcp(byte source, byte vcp, byte value) {
        byte[] p = new byte[7];
        p[0] = source; p[1] = 0x84; p[2] = 0x03; p[3] = vcp; p[4] = 0x00; p[5] = value;
        byte sum = DDC_I2C_ADDRESS;
        for (int i = 0; i < 6; i++) sum ^= p[i];
        p[6] = sum;
        return p;
    }

    // Used by -WhatIf to show the exact bytes without sending them.
    //
    // IT TAKES THE TARGET AND PASSES THE SAME GATE WriteLgInput DOES. A dry run
    // exists to show what a real run would do, and this one printed a source
    // 0x50 packet for a non-GSM panel -- a packet the transport would have
    // refused. Confirming a plan that cannot happen is worse than no dry run,
    // because ..\AGENTS.md hard rule 3 makes looking at the output the only
    // verification this hardware permits.
    public static string PacketForLgInput(NvDisplay target, byte value) {
        RefuseNonGsm(target);
        return BitConverter.ToString(BuildSetVcp(LG_I2C_SOURCE, LG_VCP_INPUT, value)).Replace("-", " ");
    }

    public static string PacketForStandardVcp(byte vcp, byte value) {
        return BitConverter.ToString(BuildSetVcp(STD_I2C_SOURCE, vcp, value)).Replace("-", " ");
    }

    // Send an LG input-select packet to ONE output.
    //
    // This is the only function in the codebase that can emit I2C source 0x50, and
    // it refuses any target whose EDID manufacturer is not GSM. The source byte is
    // not a parameter and there is no generic write entry point, so the LG service
    // channel cannot be aimed at another vendor's panel by any caller. Enforcing it
    // here rather than at the call site is deliberate: constraint 10 then holds by
    // construction instead of by discipline.
    public static int WriteLgInput(NvDisplay target, byte value) {
        RefuseNonGsm(target);
        return Send(target, BuildSetVcp(LG_I2C_SOURCE, LG_VCP_INPUT, value));
    }

    // THE GATE, in one place, so the writer and the dry run cannot disagree
    // about which panels may be shown a source 0x50 packet.
    private static void RefuseNonGsm(NvDisplay target) {
        if (target == null)
            throw new ArgumentNullException("target");
        if (target.EdidVendor != EDID_VENDOR_GSM)
            throw new InvalidOperationException(string.Format(
                "REFUSING to send LG service-channel source 0x{0:X2} to a {1} (0x{2:X4}) panel at {3}. " +
                "Only GSM (0x{4:X4}) may receive it.",
                LG_I2C_SOURCE, DecodeMfg(target.EdidVendor), target.EdidVendor, target, EDID_VENDOR_GSM));
    }

    // Send a standard DDC/CI SetVCP to ONE output, on the normal host source 0x51.
    //
    // No vendor gate, and none is needed: 0x51 is the ordinary DDC/CI channel that
    // every monitor and every OS-level tool already uses. It is 0x50 that is a
    // service channel, and WriteLgInput above is the only way to reach it.
    public static int WriteStandardVcp(NvDisplay target, byte vcp, byte value) {
        if (target == null) throw new ArgumentNullException("target");
        return Send(target, BuildSetVcp(STD_I2C_SOURCE, vcp, value));
    }

    // Framing follows lg-input-switch: the whole packet goes in pbData with no
    // separate register address. SimpleKVM instead puts the source byte in
    // pbI2cRegAddress with regAddrSize = 1 and the rest in pbData. Both projects
    // report their own shape working; lg-input-switch is the one demonstrably
    // driving THIS panel, so it won the tie -- and the LG switch confirmed it on
    // hardware. If it ever stops working, the alternative is documented in
    // ..\ideas\nvapi-transport.md -- change it here, do not add a switch.
    static int Send(NvDisplay target, byte[] packet) {
        IntPtr pData = Marshal.AllocHGlobal(packet.Length);
        try {
            Marshal.Copy(packet, 0, pData, packet.Length);

            var info = new NV_I2C_INFO();
            info.version         = (uint)(Marshal.SizeOf(typeof(NV_I2C_INFO)) | (3 << 16));
            info.displayMask     = target.OutputId;
            info.bIsDDCPort      = 1;
            info.i2cDevAddress   = DDC_I2C_ADDRESS;
            info.pbI2cRegAddress = IntPtr.Zero;
            info.regAddrSize     = 0;
            info.pbData          = pData;
            info.cbSize          = (uint)packet.Length;
            info.i2cSpeed        = 0xFFFF;   // deprecated field, must be this
            info.i2cSpeedKhz     = 0;
            info.portId          = 0;
            info.bIsPortIdSet    = 0;

            return _i2cWrite(target.Gpu, ref info);
        } finally {
            Marshal.FreeHGlobal(pData);
        }
    }
}

// --- dxva2: the vendor-neutral transport, via the desktop ------------------
//
// Windows' own DDC/CI stack. It reaches a panel on ANY adapter, which is the
// whole point of it -- NVAPI sees only panels on the NVIDIA card. Restored from
// the implementation deleted at 70e5ed4, with ONE correction: identity comes from
// the EDID vendor+product inside the PnP interface path, never the whole path.
// Moving a cable between adapters changed the path from
// DISPLAY\AUS42E0\5&aaaaaaaa&0&UID4352_0 to DISPLAY\AUS42E0\4&bbbbbbbb&0&UID49_0
// and the GDI name from \\.\DISPLAY1 to \\.\DISPLAY7; only AUS42E0 held.
//
// IT CANNOT REACH A SERVICE CHANNEL, and that is a safety property rather than a
// gap to close: SetVCPFeature takes a VCP code, never an I2C source byte, and the
// Windows stack hardcodes source 0x51. So no addition here can widen the 0x50
// surface that ..\AGENTS.md hard rule 5 protects. There is deliberately no entry
// point that takes a source or an I2C address, and conventions.tests.ps1 asserts
// it over this class as well as the one above.
//
// It needs a DESKTOP. In session 0 user32 reports one phantom named WinDisc with
// no interface path and no physical monitor handle -- so it MIS-RESOLVES rather
// than erroring, which is why matching on EDID and refusing anything but exactly
// one match is load-bearing here and not merely tidy. Measured 2026-09-01.
public class DxvaDisplay {
    public IntPtr Handle;
    public string Device;        // GDI name, e.g. \\.\DISPLAY3 -- NOT an identifier
    public string InterfacePath;
    public ushort EdidVendor;
    public ushort EdidProduct;

    public override string ToString() {
        return string.Format("device={0} edid=0x{1:X4}:0x{2:X4}", Device, EdidVendor, EdidProduct);
    }
}

public static class Dxva {
    [StructLayout(LayoutKind.Sequential)]
    public struct RECT { public int left, top, right, bottom; }

    [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
    public struct MONITORINFOEX {
        public int cbSize;
        public RECT rcMonitor;
        public RECT rcWork;
        public uint dwFlags;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 32)] public string szDevice;
    }

    [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
    public struct DISPLAY_DEVICE {
        public int cb;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 32)]  public string DeviceName;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 128)] public string DeviceString;
        public uint StateFlags;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 128)] public string DeviceID;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 128)] public string DeviceKey;
    }

    [StructLayout(LayoutKind.Sequential, CharSet = CharSet.Unicode)]
    public struct PHYSICAL_MONITOR {
        public IntPtr hPhysicalMonitor;
        [MarshalAs(UnmanagedType.ByValTStr, SizeConst = 128)] public string szDescription;
    }

    public delegate bool MonEnumProc(IntPtr hMon, IntPtr hdc, ref RECT rc, IntPtr data);

    [DllImport("user32.dll")]
    public static extern bool EnumDisplayMonitors(IntPtr hdc, IntPtr clip, MonEnumProc proc, IntPtr data);
    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    public static extern bool GetMonitorInfo(IntPtr hMon, ref MONITORINFOEX mi);
    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    public static extern bool EnumDisplayDevices(string dev, uint devNum, ref DISPLAY_DEVICE dd, uint flags);

    [DllImport("dxva2.dll", SetLastError = true)]
    public static extern bool GetNumberOfPhysicalMonitorsFromHMONITOR(IntPtr hMon, ref uint n);
    [DllImport("dxva2.dll", SetLastError = true)]
    public static extern bool GetPhysicalMonitorsFromHMONITOR(IntPtr hMon, uint n, [Out] PHYSICAL_MONITOR[] arr);
    [DllImport("dxva2.dll", SetLastError = true)]
    public static extern bool DestroyPhysicalMonitors(uint n, PHYSICAL_MONITOR[] arr);
    [DllImport("dxva2.dll", SetLastError = true)]
    public static extern bool SetVCPFeature(IntPtr hMonitor, byte code, uint value);

    const uint EDD_GET_DEVICE_INTERFACE_NAME = 1;

    static string InterfacePath(string deviceName) {
        var dd = new DISPLAY_DEVICE();
        dd.cb = Marshal.SizeOf(typeof(DISPLAY_DEVICE));
        if (!EnumDisplayDevices(deviceName, 0, ref dd, EDD_GET_DEVICE_INTERFACE_NAME)) return "";
        return dd.DeviceID ?? "";
    }

    static string DeviceOf(IntPtr hMon) {
        var mi = new MONITORINFOEX();
        mi.cbSize = Marshal.SizeOf(typeof(MONITORINFOEX));
        if (!GetMonitorInfo(hMon, ref mi)) return "";
        return mi.szDevice ?? "";
    }

    // "AUS42E0" out of \\?\DISPLAY#AUS42E0#5&aaaaaaaa&0&UID4352#{guid}, then split
    // into the packed 5-bit vendor word and the product id. That word is the same
    // one the config stores and NvDdc.DecodeMfg renders, so both transports match
    // on one key and a per-panel transport choice needs no second identity.
    // Returns false for anything that does not parse -- including the session-0
    // phantom, whose path is empty.
    public static bool ParseEdid(string path, out ushort vendor, out ushort product) {
        vendor = 0; product = 0;
        if (string.IsNullOrEmpty(path)) return false;
        string[] parts = path.Split('#');
        if (parts.Length < 2) return false;
        string id = parts[1];
        if (id.Length < 7) return false;
        string letters = id.Substring(0, 3).ToUpperInvariant();
        int v = 0;
        for (int i = 0; i < 3; i++) {
            int c = letters[i] - 64;
            if (c < 1 || c > 26) return false;
            v = (v << 5) | c;
        }
        ushort p;
        if (!ushort.TryParse(id.Substring(3, 4), System.Globalization.NumberStyles.HexNumber,
                             System.Globalization.CultureInfo.InvariantCulture, out p)) return false;
        vendor  = (ushort)v;
        product = p;
        return true;
    }

    public static List<DxvaDisplay> Enumerate() {
        var handles = new List<IntPtr>();
        EnumDisplayMonitors(IntPtr.Zero, IntPtr.Zero,
            delegate(IntPtr h, IntPtr hdc, ref RECT rc, IntPtr d) { handles.Add(h); return true; },
            IntPtr.Zero);

        var found = new List<DxvaDisplay>();
        foreach (IntPtr h in handles) {
            string dev  = DeviceOf(h);
            string path = InterfacePath(dev);
            ushort vendor, product;
            // No identity, no entry. A monitor we cannot name is one we must never
            // aim at, and in session 0 every monitor looks like this.
            if (!ParseEdid(path, out vendor, out product)) continue;
            var d2 = new DxvaDisplay();
            d2.Handle = h; d2.Device = dev; d2.InterfacePath = path;
            d2.EdidVendor = vendor; d2.EdidProduct = product;
            found.Add(d2);
        }
        return found;
    }

    // Write only. There is deliberately no GetVCPFeature wrapper: reads on this
    // hardware produce false negatives and must never gate a switch (hard rule 2).
    // Returns the number of physical monitors that accepted, or negative on
    // failure to obtain a handle at all.
    public static int WriteStandardVcp(DxvaDisplay target, byte code, byte value) {
        uint n = 0;
        if (!GetNumberOfPhysicalMonitorsFromHMONITOR(target.Handle, ref n) || n == 0) return -1;
        // EXACTLY ONE, or refuse. In "Duplicate these displays" one HMONITOR
        // carries several physical panels, and identity was read from the first
        // of them -- so a write aimed at one panel reached every panel behind
        // the handle. Both switchers address exactly one display
        // (specs/config-format.md), and a handle that names more than one
        // cannot be aimed.
        if (n != 1) return -3;
        var arr = new PHYSICAL_MONITOR[n];
        if (!GetPhysicalMonitorsFromHMONITOR(target.Handle, n, arr)) return -2;
        try {
            int ok = 0;
            foreach (var pm in arr) {
                if (SetVCPFeature(pm.hPhysicalMonitor, code, (uint)value)) ok++;
            }
            // ZERO ACCEPTED IS NOT SUCCESS. `ok` was returned raw and the caller
            // mapped anything non-positive to itself, so 0 -- every write
            // refused -- came back as 0, which is the success code.
            return ok > 0 ? 0 : -4;
        } finally {
            DestroyPhysicalMonitors(n, arr);
        }
    }
}
