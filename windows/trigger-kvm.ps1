# Load the transport, once per PowerShell process.
#
# .NET cannot replace a type once it is loaded into an AppDomain. That matters here
# because of how this script gets verified: you edit it and re-run it in the same
# shell. A bare Add-Type throws "type name 'NvDisplay' already exists" on the second
# run, and the tempting fix -- skip Add-Type when the type is already present -- is
# WORSE than the error. It would silently run the previously loaded transport, so a
# hand-verified switch would be confirming code that is not the code on disk. Given
# that hand-verification is the only verification this hardware permits (hard rule
# 3), a false pass is the most expensive failure available here.
#
# So: stamp the loaded types with a hash of the source they came from, and refuse
# loudly if this session already holds a different version. Re-running the SAME
# version in one session is fine and reuses what is loaded. The installed path never
# reaches any of this -- the task starts a fresh powershell.exe per switch.
$stampKey = 'trigger-kvm:NvDdcSourceStamp'
$stamp    = $TransportSource.GetHashCode()

if ('NvDdc' -as [type]) {
    if ([AppDomain]::CurrentDomain.GetData($stampKey) -ne $stamp) {
        throw ("This PowerShell session already loaded trigger-kvm's types from a " +
               "DIFFERENT version of this script, and .NET cannot replace a loaded type. " +
               "Open a new PowerShell window and re-run: continuing here would test the " +
               "old code while appearing to test the new.")
    }
} else {
    Add-Type -ErrorAction Stop -TypeDefinition $TransportSource
    [AppDomain]::CurrentDomain.SetData($stampKey, $stamp)
}

# --- resolving a panel ------------------------------------------------------

# Find the one connected output whose EDID matches, or $null with the reason logged.
#
# Fails closed on both sides of "exactly one". Zero is a refusal for the obvious
# reason. More than one is also a refusal: an ambiguous target cannot be aimed at,
# and picking the first would reintroduce exactly the order-dependence that this
# repo's conventions forbid.
#
# This replaces the old Test-LgBlastRadius, which existed only to compensate for
# lg-input-switch spraying VCP 0xF4 at every connected output. An aimed write has no
# blast radius, so the check is no longer "is anything unrecognised attached" -- it
# is the narrower and stronger "is the intended panel positively identified". A
# third monitor being attached is now simply irrelevant.
#
# One resolver for both transports. They differ only in how the candidates are
# enumerated and what a failure to enumerate at all is called; "exactly one EDID
# match or refuse" is the same rule and must stay one implementation, because it
# is the rule that turns session 0's phantom into a refusal rather than a mis-aim.
function Resolve-Panel {
    param([int]$Vendor, [int]$Product, [string]$Name, [string]$Transport = 'nvapi')

    $all = $null
    switch ($Transport) {
        'nvapi' {
            $status = [NvDdc]::Init()
            if ($status -ne 'OK') {
                Write-Log "REFUSING $Name switch: NVAPI unavailable -- $status"
                return $null
            }
            $all = @([NvDdc]::Enumerate())
        }
        'dxva2' {
            # No Init to fail: user32 always answers. What it answers with in
            # session 0 is one phantom carrying no interface path, which
            # Dxva.Enumerate drops for having no identity -- so the failure mode
            # here is an empty list and a named refusal, not a wrong target.
            $all = @([Dxva]::Enumerate())
        }
        default {
            # A caller bug, not a config problem: Switch-Display validates the
            # transport before anything reaches here. Throwing rather than logging
            # a refusal keeps the two distinguishable -- and keeps the rule about
            # which transports exist in exactly one place, so a mutation of it
            # cannot be masked by a second copy here.
            throw "Resolve-Panel called with an unvalidated transport '$Transport'"
        }
    }

    $match = @($all | Where-Object {
        $_.EdidVendor -eq $Vendor -and $_.EdidProduct -eq $Product
    })

    if ($match.Count -eq 1) { return $match[0] }

    if ($match.Count -eq 0) {
        $seen = if ($all.Count) { ($all | ForEach-Object { $_.ToString() }) -join '; ' } else { 'nothing' }
        Write-Log ("REFUSING {0} switch: no output identifies as it (EDID 0x{1:X4}:0x{2:X4}). {3} enumerated: {4}" -f `
                   $Name, $Vendor, $Product, $Transport.ToUpperInvariant(), $seen)
    } else {
        Write-Log ("REFUSING {0} switch: {1} outputs identify as it, so the target is ambiguous: {2}" -f `
                   $Name, $match.Count, (($match | ForEach-Object { $_.ToString() }) -join '; '))
    }
    return $null
}

# Send one panel's input-select packet, twice. DDC is lossy and the writes are
# idempotent, so a repeat is free and covers a dropped byte.
#
# Untyped $Target on purpose: it is an NvDisplay or a DxvaDisplay, and all this
# needs of either is a ToString() for the log and the ShouldProcess line. Retry,
# -WhatIf and logging stay HERE rather than in each transport, so the two cannot
# drift in how a switch is reported or how often it is attempted.
function Invoke-Switch {
    param(
        $Target,
        [string]$What,
        [scriptblock]$Write
    )

    if (-not $PSCmdlet.ShouldProcess($Target.ToString(), $What)) {
        Write-Log "WHATIF: would send $What"
        return $true
    }

    $ok = 0
    for ($i = 0; $i -lt $Tries; $i++) {
        try {
            if ((& $Write) -eq 0) { $ok++ }
        } catch {
            # The vendor gate throwing is a bug in the caller, not a transient
            # failure. Surface it rather than retrying into it.
            Write-Log ("ERROR: write refused: {0}" -f $_.Exception.Message)
            return $false
        }
    }

    if ($ok -eq 0) {
        Write-Log ("ERROR: {0} -- NvAPI_I2CWrite reported failure on every attempt" -f $What)
        return $false
    }
    Write-Log $What
    return $true
}

# One display, one input value. Two axes decide which write is sent -- the METHOD
# (what is sent) and the TRANSPORT (how it gets there) -- and that is ALL either
# changes. Resolution, aiming, retry, -WhatIf and logging are identical
# throughout.
#
# The pairing is a 2x2 with one impossible cell, and the impossible one is a
# safety property rather than a gap: dxva2 has no way to express an I2C source
# byte, so it cannot carry lg-alt and cannot be used to reach 0x50 at all. That
# combination is refused HERE with the reason named, rather than quietly sending
# the standard command instead -- someone who asked for a sidechannel and silently
# got something else would confirm by eye that a panel moved, and be wrong about
# what moved it.
#
# `lg-alt` grants nothing on its own axis either: NvDdc.WriteLgInput still refuses
# a panel whose EDID manufacturer is not GSM. Putting method = lg-alt on a Dell
# makes the write throw; it does not make it happen.
function Switch-Display {
    param([PSCustomObject]$Display, [byte]$Value)

    if ($null -eq $Display.Vendor -or $null -eq $Display.Product) {
        Write-Log ("REFUSING {0}: its config has no usable EDID vendor/product. Fix display.{0}.vendor and .product." -f $Display.Label)
        return $false
    }

    # VALIDATE THE PAIRING ONCE, before anything enumerates, against the one
    # transport table in config.ps1. Both switch statements below still carry a
    # default, but they are unreachable defence.
    if ($Display.Transport -notin $TRANSPORT_NAMES) {
        Write-Log ("REFUSING {0}: unknown transport '{1}'. Use {2}." -f `
                   $Display.Label, $Display.Transport, ((@($TRANSPORT_NAMES | ForEach-Object { "'$_'" })) -join ' or '))
        return $false
    }

    # A transport that cannot address an I2C source byte cannot carry a
    # manufacturer dialect. Refused naming the reason, never silently downgraded
    # to the standard command: somebody would confirm a panel moved and be wrong
    # about what moved it (specs/config-format.md, docs/decisions/003).
    if ($Display.Method -eq 'lg-alt' -and $Display.Transport -in $SOURCELESS_TRANSPORTS) {
        Write-Log (("REFUSING {0}: method 'lg-alt' needs an I2C source byte and transport '{1}' cannot send one. " +
                    "Use transport = nvapi for this panel, or method = standard.") -f $Display.Label, $Display.Transport)
        return $false
    }

    $target = Resolve-Panel -Vendor $Display.Vendor -Product $Display.Product `
                            -Name $Display.Name -Transport $Display.Transport
    if (-not $target) { return $false }

    switch ($Display.Transport) {
        'nvapi' {
            switch ($Display.Method) {
                'lg-alt' {
                    # The packet builder passes the vendor gate, so this throws
                    # for a non-GSM panel BEFORE anything is printed -- a dry
                    # run shows what a real run would do, or it is worse than
                    # no dry run at all.
                    try {
                        $what = '{0} -> src 0x50, VCP 0xF4 = 0x{1:X2} on outputId 0x{2:X8} [{3}]' -f `
                                $Display.Name, $Value, $target.OutputId, [NvDdc]::PacketForLgInput($target, $Value)
                    } catch {
                        Write-Log ("REFUSING {0}: {1}" -f $Display.Label, $_.Exception.InnerException.Message)
                        return $false
                    }
                    return Invoke-Switch -Target $target -What $what -Write {
                        [NvDdc]::WriteLgInput($target, $Value)
                    }
                }
                'standard' {
                    $what = '{0} -> src 0x51, VCP 0x60 = 0x{1:X2} on outputId 0x{2:X8} [{3}]' -f `
                            $Display.Name, $Value, $target.OutputId, [NvDdc]::PacketForStandardVcp([byte]0x60, $Value)
                    return Invoke-Switch -Target $target -What $what -Write {
                        [NvDdc]::WriteStandardVcp($target, [byte]0x60, $Value)
                    }
                }
                default {
                    Write-Log ("REFUSING {0}: unknown method '{1}'. Use 'standard' or 'lg-alt'." -f $Display.Label, $Display.Method)
                    return $false
                }
            }
        }
        'dxva2' {
            # No packet to print: dxva2 builds the DDC frame itself, so what is
            # logged is the call, not the bytes. Say so rather than inventing a
            # packet string that would look like the NVAPI ones and be a fiction.
            if ($Display.Method -ne 'standard') {
                Write-Log ("REFUSING {0}: unknown method '{1}'. Use 'standard' or 'lg-alt'." -f $Display.Label, $Display.Method)
                return $false
            }
            $what = '{0} -> dxva2 SetVCPFeature, VCP 0x60 = 0x{1:X2} on {2}' -f `
                    $Display.Name, $Value, $target.Device
            return Invoke-Switch -Target $target -What $what -Write {
                # 0 is success and every other value is a failure, which is what
                # Invoke-Switch expects. The mapping used to live here and got it
                # backwards -- `if ($n -gt 0) { 0 } else { $n }` returned $n,
                # which is 0 when NOTHING accepted the write, so a panel that
                # took none of them was logged as switched.
                [Dxva]::WriteStandardVcp($target, [byte]0x60, $Value)
            }
        }
        default {
            Write-Log ("REFUSING {0}: unknown transport '{1}'." -f $Display.Label, $Display.Transport)
            return $false
        }
    }
}

# How many ATTACHED panels answer to one EDID identity, folded across transports.
#
# The count is the MAXIMUM across transports and never the sum. Each transport
# enumerates each panel exactly once, so summing would report every ordinary panel
# on every desk as two -- which is the trap specs/configure.md 6.4 names, and the
# reason the rows above are unioned on the identity in the first place.
#
# Two panels reporting one pair is the case this exists for: the switcher already
# refuses such a target (Resolve-Panel), and this is what lets `list`, `configure`
# and `status` say so instead of the refusal only reaching the log.
function Merge-PanelTally {
    param([hashtable]$Into, [hashtable]$From)
    foreach ($k in $From.Keys) {
        if (-not $Into.Contains($k) -or $Into[$k] -lt $From[$k]) { $Into[$k] = $From[$k] }
    }
    return $Into
}

# --- main -------------------------------------------------------------------

# `list` reads nothing from the config and writes nothing to any monitor. It exists
# so you can see what is actually attached, in the exact form the config wants --
# and so the installer has one place to get that from rather than a second copy of
# the NVAPI bindings.
if (-not $Config) { $Config = Get-ConfigPath }

if ($Command -eq 'list') {
    # BOTH transports, unioned on the EDID pair -- which is the one key both read
    # (specs/config-format.md). A panel is not "on" a transport: it is REACHABLE BY
    # a set of them, often both, and which to use is then a choice someone makes
    # rather than a fact to discover. That is what makes configure able to offer.
    #
    # NVAPI being unavailable is no longer fatal here. A machine with no NVIDIA
    # card is exactly the machine this transport was added for, and `list` refusing
    # on it would make the whole walkthrough unreachable there.
    $rows   = [ordered]@{}
    # How many attached panels answer to each identity. Folded per transport and
    # then merged by MAXIMUM -- see Merge-PanelTally for why it is not a sum.
    $panels = @{}
    $status = [NvDdc]::Init()
    if ($status -eq 'OK') {
        $tally = @{}
        foreach ($d in @([NvDdc]::Enumerate())) {
            $key = '{0:X4}:{1:X4}' -f $d.EdidVendor, $d.EdidProduct
            $tally[$key] = 1 + $(if ($tally.Contains($key)) { $tally[$key] } else { 0 })
            # Twins overwrite each other here, and that is correct: they are
            # identical in every field this row carries. $panels is what remembers
            # there was more than one, because it is the only thing that can.
            $rows[$key] = [PSCustomObject]@{
                Vendor = $d.EdidVendor; Product = $d.EdidProduct
                Connector = $d.Connector; Serial = $d.EdidSerial; Name = $d.EdidName
                Transports = @('nvapi'); Panels = 1
            }
        }
        $panels = Merge-PanelTally -Into $panels -From $tally
    } else {
        Write-Log "NVAPI unavailable -- $status (continuing; dxva2 does not need it)"
    }

    $tally = @{}
    foreach ($d in @([Dxva]::Enumerate())) {
        $key = '{0:X4}:{1:X4}' -f $d.EdidVendor, $d.EdidProduct
        $tally[$key] = 1 + $(if ($tally.Contains($key)) { $tally[$key] } else { 0 })
        if ($rows.Contains($key)) {
            $rows[$key].Transports = @($rows[$key].Transports) + 'dxva2'
        } else {
            # dxva2 knows no connector and no serial -- it reads identity out of the
            # PnP path, which carries neither. Say '-' rather than inventing one.
            $rows[$key] = [PSCustomObject]@{
                Vendor = $d.EdidVendor; Product = $d.EdidProduct
                Connector = '-'; Serial = 0; Name = ''
                Transports = @('dxva2'); Panels = 1
            }
        }
    }
    $panels = Merge-PanelTally -Into $panels -From $tally

    foreach ($key in @($rows.Keys)) {
        if ($panels.Contains($key)) { $rows[$key].Panels = $panels[$key] }
    }

    $found = @($rows.Values)
    if ($found.Count -eq 0) { Write-Log 'no connected displays found by any transport'; exit 2 }

    if ($Raw) {
        foreach ($d in $found) {
            # Fields append-only: install.ps1 accepts >= 4, so a copy of it that
            # predates a field still works. Panels last, for that reason -- an
            # older installer reads six fields and behaves exactly as it did.
            Write-Output ('{0:X4}|{1:X4}|{2}|{3}|{4:X8}|{5}|{6}|{7}' -f `
                          $d.Vendor, $d.Product, [NvDdc]::DecodeMfg($d.Vendor),
                          $d.Connector, $d.Serial, $d.Name, ($d.Transports -join ','),
                          $d.Panels)
        }
        exit 0
    }

    $known = @{}
    foreach ($d in (Get-ConfiguredDisplays -Cfg (Read-Config -Path $Config))) {
        if ($null -ne $d.Vendor -and $null -ne $d.Product) {
            $known[('{0:X4}:{1:X4}' -f $d.Vendor, $d.Product)] = $d.Label
        }
    }

    Write-Host ''
    Write-Host ('  {0,-8} {1,-9} {2,-11} {3,-22} {4,-15} {5}' -f 'vendor', 'product', 'connector', 'name (from the panel)', 'reachable by', 'configured as')
    Write-Host ('  {0,-8} {1,-9} {2,-11} {3,-22} {4,-15} {5}' -f '------', '-------', '---------', '---------------------', '------------', '-------------')
    foreach ($d in $found) {
        $key = '{0:X4}:{1:X4}' -f $d.Vendor, $d.Product
        Write-Host ('  0x{0:X4}   0x{1:X4}    {2,-11} {3,-22} {4,-15} {5}' -f `
                    $d.Vendor, $d.Product, $d.Connector,
                    $(if ($d.Name) { $d.Name } else { '(' + [NvDdc]::DecodeMfg($d.Vendor) + ', unnamed)' }),
                    ($d.Transports -join ', '),
                    $(if ($known.Contains($key)) { $known[$key] } else { '-- not in config --' }))
    }
    Write-Host ''

    # The row above is one row per IDENTITY, so two identical panels are one line
    # and the second would otherwise be invisible -- specs/configure.md 6.4. The
    # count is what makes it visible; the table keeps its shape.
    foreach ($d in $found) {
        if ($d.Panels -le 1) { continue }
        Write-Host ('  !! {0} monitors report the same id and cannot be told apart (0x{1:X4}:0x{2:X4}).' -f `
                    $d.Panels, $d.Vendor, $d.Product)
        Write-Host  '     A switch cannot aim at one of them, so none of them can be managed.'
        Write-Host  '     Unplug one to manage the other.'
        Write-Host ''
    }
    Write-Host 'To add one, put this in the config and name the input each computer is on:'
    Write-Host ''
    $ex = $found[0]
    Write-Host ('    display.<label>.vendor  = 0x{0:X4}' -f $ex.Vendor)
    Write-Host ('    display.<label>.product = 0x{0:X4}' -f $ex.Product)
    Write-Host  '    display.<label>.name    = <a name for logs>'
    Write-Host  '    display.<label>.method  = standard        # or lg-alt, for an LG whose 0x60 is stubbed'
    Write-Host ('    display.<label>.transport = {0,-8}      # how the bytes get there; omit for nvapi' -f $ex.Transports[0])
    Write-Host  '    display.<label>.input.0x11 = pc           # name each input after what is plugged in'
    Write-Host  '    display.<label>.input.0x0f = mac          # `pull` uses computer.this; `to mac` uses this'
    Write-Host ''
    Write-Host 'NOTE: some panels report a DIFFERENT product id per input -- the LG 45GX950A does.'
    Write-Host 'Use the value shown HERE, measured on this computer. Never copy one from another host.'
    exit 0
}

if (-not $Config) { $Config = Get-ConfigPath }
$cfg      = Read-Config -Path $Config
$displays = @(Get-ConfiguredDisplays -Cfg $cfg)
# What this config calls the machine it is running on. `pull` is `to $ThisComputer`.
$ThisComputer = $(if ($cfg.Contains('computer.this')) { "$($cfg['computer.this'])".Trim().ToLower() } else { '' })

if ($displays.Count -eq 0) {
    Write-Log ("no displays configured. Expected a config at {0}; run install.ps1 to generate one." -f $Config)
    exit 2
}

if ($Only -ne 'all') {
    $displays = @($displays | Where-Object { $_.Label -eq $Only })
    if ($displays.Count -eq 0) {
        Write-Log ("no configured display labelled '{0}'. Known: {1}" -f `
                   $Only, ((Get-ConfiguredDisplays -Cfg $cfg | ForEach-Object { $_.Label }) -join ', '))
        exit 2
    }
}

# Resolve every value BEFORE sending anything. A machine that two displays know
# about and a third does not moves neither -- a half-applied arrangement is worse
# than none, because it leaves the desk in a state nobody configured and the user
# has to work out which half landed.
$plan = @()
foreach ($d in $displays) {
    if ($Command -eq 'set') {
        if ($displays.Count -ne 1) {
            Write-Log 'set requires -Only naming exactly one display'
            exit 2
        }
        $value = ConvertTo-Byte $Value
        if ($null -eq $value) {
            Write-Log ("REFUSING: -Value '{0}' is not a byte (use 0x11 or 17)." -f $Value)
            exit 2
        }
    }
    else {
        # pull and to are the same operation: point every display at a named machine.
        # pull looks up the one this config calls itself, to looks up the one you
        # asked for. There is no second table and no second code path.
        $who = if ($Command -eq 'pull') { $ThisComputer } else { "$Computer".ToLower() }
        if (-not $who) {
            if ($Command -eq 'pull') {
                Write-Log ("REFUSING: computer.this is missing from {0}. Run: trigger-kvm configure" -f $Config)
            } else {
                Write-Log 'usage: trigger-kvm.ps1 to <computer>'
            }
            exit 2
        }
        if (-not $d.Inputs.Contains($who)) {
            $known = @($d.Inputs.Keys | Sort-Object)
            Write-Log ("REFUSING: '{0}' has no input named '{1}' ({2}). Nothing was sent." -f `
                       $d.Label, $who,
                       $(if ($known) { 'it knows: ' + ($known -join ', ') }
                         else        { 'it names no computers at all' }))
            exit 2
        }
        $value = $d.Inputs[$who]
        if ($value -eq 'AMBIGUOUS') {
            Write-Log ("REFUSING: '{0}' names '{1}' on more than one input. Fix {2}." -f $d.Label, $who, $Config)
            exit 2
        }
    }
    $plan += [PSCustomObject]@{ Display = $d; Value = $value }
}

$rc = 0
foreach ($step in $plan) {
    if (-not (Switch-Display -Display $step.Display -Value $step.Value)) { $rc = 1 }
}

# A zero exit means the writes were sent, NOT that the monitors switched. There is
# no way to verify that from here: reads on this hardware lie. Confirm visually.
exit $rc
